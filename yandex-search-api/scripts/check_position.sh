#!/usr/bin/env bash
# Найти позицию домена в выдаче по запросу.
# Использование: ./check_position.sh "денник для лошади купить" "konix.su"
source "$(dirname "$0")/common.sh"

QUERY="${1:?Укажите запрос}"
DOMAIN="${2:?Укажите домен для поиска в выдаче}"

log "Получаем выдачу и ищем домен $DOMAIN..."
log "Реализация парсинга base64/XML-ответа зависит от точного формата — см. search.sh и"
log "документацию Yandex Cloud Search API для распаковки результатов перед сравнением с доменом."

"$(dirname "$0")/search.sh" "$QUERY"
